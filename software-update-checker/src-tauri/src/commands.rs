/// 保存先を利用者に選ばせる（バックエンド側でダイアログを出す）。
/// 画面からパスを受け取って書き込むと、画面が乗っ取られた場合に任意の場所へ書き込まれるため、
/// 書き込み先は必ずこのダイアログで利用者が選んだものに限る。キャンセルなら `None`。
fn ask_save_path(app: &AppHandle, title: String, filter: &str, extension: &str, default_name: &str) -> Result<Option<PathBuf>, String> {
    // 既定のファイル名にパスが混ざっていても、ファイル名部分だけを使う
    let name = std::path::Path::new(default_name)
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| format!("export.{extension}"));
    match app
        .dialog()
        .file()
        .set_title(title)
        .add_filter(filter, &[extension])
        .set_file_name(name)
        .blocking_save_file()
    {
        Some(p) => p.into_path().map(Some).map_err(|e| e.to_string()),
        None => Ok(None),
    }
}

#[tauri::command]
pub async fn import_file(http: State<'_, Http>, path: String) -> Result<ImportResult, String> {
    let p = path.clone();
    let result = tauri::async_runtime::spawn_blocking(move || importers::import_file(&PathBuf::from(p)))
        .await
        .map_err(|e| e.to_string())?;
    match &result {
        Ok(r) => http.log().info(tr!("取り込み: {path}（{}、{} 件）", "Imported: {path} ({}, {} components)", r.format, r.components.len())),
        Err(e) => http.log().info(tr!("取り込み失敗: {path}: {e}", "Import failed: {path}: {e}")),
    }
    result
}

/// pom.xml のあるプロジェクトで Maven を実行して SBOM を生成し、取り込む。
#[tauri::command]
pub async fn generate_sbom_with_maven(
    http: State<'_, Http>,
    pom_path: String,
    options: CheckOptions,
) -> Result<ImportResult, String> {
    if !options.source_enabled(sources::MAVEN_LOCAL) {
        return Err(tr!(
            "データソース「ローカルの Maven」が設定で無効になっています。",
            "The data source \"Local Maven\" is disabled in the settings."
        ));
    }
    let http = http.inner().clone();
    tauri::async_runtime::spawn_blocking(move || {
        let bom = importers::maven::generate_sbom(&PathBuf::from(&pom_path), http.log())?;
        let mut result = importers::import_file(&bom)?;
        result
            .warnings
            .insert(0, tr!("{pom_path} から Maven で生成した SBOM（{}）です。", "SBOM generated by Maven from {pom_path} ({}).", bom.display()));
        Ok(result)
    })
    .await
    .map_err(|e| e.to_string())?
}

/// チェックを実行する。進捗は `check-progress` イベントで通知する。
#[tauri::command]
pub async fn run_checks(
    app: AppHandle,
    http: State<'_, Http>,
    components: Vec<Component>,
    options: CheckOptions,
) -> Result<Vec<CheckResult>, String> {
    http.configure(&options);
    let progress: checks::ProgressFn = Arc::new(move |p: CheckProgress| {
        let _ = app.emit("check-progress", p);
    });
    let results = checks::run_checks(&http, &components, &options, progress).await;
    if let Err(e) = http.save().await {
        eprintln!("キャッシュを保存できませんでした: {e}");
    }
    Ok(results)
}

/// 指定バージョンに必要な Java を答える（Maven のみ）。ナレッジに記録があればそれを使い、
/// 無ければ Maven Central の jar から判定してナレッジに記録する。
#[tauri::command]
pub async fn java_requirements(
    http: State<'_, Http>,
    store: State<'_, KnowledgeStore>,
    component: Component,
    versions: Vec<String>,
    options: CheckOptions,
) -> Result<Vec<JavaRequirement>, String> {
    if component.ecosystem != Ecosystem::Maven {
        return Ok(Vec::new());
    }
    let Some(group) = component.group.as_deref() else { return Ok(Vec::new()) };
    http.configure(&options);
    let can_fetch = options.source_enabled(sources::MAVEN_CENTRAL);
    let shared = knowledge::load_shared(&options.shared_knowledge_files);
    let mut out = Vec::new();
    for v in versions {
        out.push(checks::java::resolve(&http, &store, &shared, group, &component.name, &v, can_fetch).await);
    }
    Ok(out)
}

#[derive(serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct KnowledgeView {
    pub local_path: Option<String>,
    pub local_error: Option<String>,
    pub local: Vec<JavaRule>,
    pub shared: Vec<SharedFile>,
}

/// 手元と共有の Java 要件ナレッジ。
#[tauri::command]
pub fn knowledge_list(store: State<'_, KnowledgeStore>, shared_files: Vec<String>) -> KnowledgeView {
    KnowledgeView {
        local_path: store.path().map(|p| p.display().to_string()),
        local_error: store.load_error().map(str::to_string),
        local: store.entries(),
        shared: knowledge::load_shared(&shared_files),
    }
}

/// 手動の追加・修正。`original` は編集前の記録（対象を変えた場合に置き換える）。
#[tauri::command]
pub fn knowledge_upsert(
    http: State<'_, Http>,
    store: State<'_, KnowledgeStore>,
    rule: JavaRule,
    original: Option<RuleKey>,
) -> Result<(), String> {
    let unknown = tr!("不明", "unknown");
    let label = format!("{} → Java {}", rule.scope_label(), rule.java.as_deref().unwrap_or(&unknown));
    store.upsert(rule, original)?;
    http.log().info(tr!("Java 要件ナレッジを登録: {label}", "Java requirement registered: {label}"));
    Ok(())
}

#[tauri::command]
pub fn knowledge_delete(http: State<'_, Http>, store: State<'_, KnowledgeStore>, key: RuleKey) -> Result<bool, String> {
    let deleted = store.delete(&key)?;
    if deleted {
        http.log().info(tr!(
            "Java 要件ナレッジを削除: {}:{} {}",
            "Java requirement deleted: {}:{} {}",
            key.group,
            key.artifact,
            key.version.or(key.series).unwrap_or_default()
        ));
    }
    Ok(deleted)
}

/// 他のナレッジファイルを手元に取り込む（手元の手動記録は上書きしない）。
#[tauri::command]
pub fn knowledge_import(http: State<'_, Http>, store: State<'_, KnowledgeStore>, path: String) -> Result<MergeSummary, String> {
    let file = knowledge::KnowledgeFile::read(std::path::Path::new(&path))?;
    let summary = store.merge(file.entries)?;
    http.log().info(tr!(
        "Java 要件ナレッジを取り込み: {path}（追加 {}、更新 {}、手動記録と衝突して見送り {}）",
        "Java requirements imported from {path} (added {}, updated {}, skipped {} conflicting with manual records)",
        summary.added, summary.updated, summary.skipped
    ));
    Ok(summary)
}

#[derive(serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExportResult {
    pub path: String,
    pub count: usize,
}

/// 手元のナレッジを書き出す（共有用）。保存先はこの中で利用者に選ばせる。
/// `include_detected` が false なら手動の記録だけ。キャンセルなら `None`。
#[tauri::command]
pub async fn knowledge_export(
    app: AppHandle,
    http: State<'_, Http>,
    store: State<'_, KnowledgeStore>,
    include_detected: bool,
) -> Result<Option<ExportResult>, String> {
    let title = tr!("Java 要件ナレッジの書き出し先", "Export Java requirements to");
    let Some(path) = ask_save_path(&app, title, "JSON", "json", "java-requirements.json")? else {
        return Ok(None);
    };
    let count = store.export(&path, include_detected)?;
    let shown = path.display().to_string();
    http.log().info(tr!("Java 要件ナレッジを書き出し: {shown}（{count} 件）", "Java requirements exported to {shown} ({count} records)"));
    Ok(Some(ExportResult { path: shown, count }))
}

