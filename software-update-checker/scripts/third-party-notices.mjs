// THIRD-PARTY-NOTICES.txt を生成する（npm run notices）。
//
// - Rust: cargo-about で、実行ファイルにリンクされるクレートのライセンス本文を集める
//   （設定は about.toml、書式は about.hbs。cargo install --locked cargo-about が必要）
// - npm: 画面の JavaScript に同梱されるパッケージ（dependencies と、コンパイル後も
//   ランタイムが残る svelte）のライセンス本文を node_modules から集める
//
// 生成物はリポジトリに入れ、アプリの「このソフトウェアについて」でも表示する。
// 依存を更新したら、このスクリプトを実行して差分をコミットすること。

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

// ---- Rust
const rust = execFileSync(
  'cargo',
  // --offline: Cargo.lock のとおりに処理し、ネットワークに出ない。--fail: ライセンスを判定できないクレートがあれば失敗させる
  ['about', 'generate', '--offline', '--fail', '--manifest-path', 'src-tauri/Cargo.toml', '--config', 'about.toml', 'about.hbs'],
  { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 64 * 1024 * 1024 },
);

// ---- npm（画面に同梱されるもの）
const bundled = [...Object.keys(pkg.dependencies ?? {}), 'svelte'].sort();
const npmSections = bundled.map((name) => {
  const dir = join(root, 'node_modules', name);
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const licenseFiles = readdirSync(dir).filter((f) => /^(LICEN[CS]E|COPYING)/i.test(f)).sort();
  if (licenseFiles.length === 0) throw new Error(`${name} にライセンスファイルがありません`);
  const texts = licenseFiles.map((f) => `[${f}]\n\n${readFileSync(join(dir, f), 'utf8').trim()}`);
  const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url;
  return [
    '-'.repeat(80),
    `${name} ${meta.version} (${meta.license})${repo ? ` <${repo.replace(/^git\+/, '')}>` : ''}`,
    '',
    texts.join('\n\n'),
    '',
  ].join('\n');
});

const header = `Third-party notices for software-update-checker ${pkg.version}

software-update-checker is licensed under the Apache License, Version 2.0.
It includes the open source components listed below, each under its own
license. This file is generated by scripts/third-party-notices.mjs.

`;

const npm = `
${'='.repeat(80)}
npm packages bundled into the user interface
${'='.repeat(80)}

${npmSections.join('\n')}`;

const out = (header + rust + npm).replace(/\r\n/g, '\n').replace(/\n{3,}/g, '\n\n');
const target = join(root, 'THIRD-PARTY-NOTICES.txt');
writeFileSync(target, out, 'utf8');
console.log(`wrote ${target} (${Buffer.byteLength(out)} bytes)`);
