const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { ja, en };

/** 現在の表示言語の文言。画面の中で呼べば、言語を切り替えたときに表示も変わる。 */
export function t(key: MessageKey, params?: Record<string, string | number | null | undefined>): string {
  const text = DICTIONARIES[prefs.locale]?.[key] ?? ja[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? whole : String(value);
  });
}
